    // 계약: LocStrings.LookupReason 과 같은 원문을 받는다 — 모르는 값은 원문 그대로 보인다
    private static string LookupReason(string reason) => reason switch
    {
        "token expired, Claude CLI not found" => "令牌过期 · 未找到 Claude CLI",
        "token expired, CLI refresh timed out" => "令牌过期 · CLI 刷新超时",
        "token expired, CLI refresh could not start" => "令牌过期 · 无法启动 CLI 刷新",
        "token expired, CLI refresh did not renew it" => "令牌过期 · CLI 刷新失败（需重新关联）",
        "HTTP 401" => "HTTP 401 · 令牌被拒绝（需重新关联）",
        "HTTP 403" => "HTTP 403 · 无权限（需重新关联）",
        "HTTP 429" => "HTTP 429 · 请求过多（自动重试）",
        _ => reason.Replace("token expired", "令牌过期"),
    };

    public static readonly (Regex Pattern, Func<Match, string> Replace)[] Patterns =
    [
        (new Regex(@"^Resets now$"), _ => "即将重置"),
        (new Regex(@"^Resets in (.+)$"), m => $"{Loc.Duration(m.Groups[1].Value)}后重置"),
        (new Regex(@"^Pace: (.+?)(?: · (.+))?$"), m => m.Groups[2].Success
            ? $"进度：{Pace(m.Groups[1].Value)} · {Pace(m.Groups[2].Value)}"
            : $"进度：{Pace(m.Groups[1].Value)}"),
        (new Regex(@"^(\d+)% used$"), m => $"已用 {m.Groups[1].Value}%"),
        (new Regex(@"^Updated just now$"), _ => "刚刚更新"),
        (new Regex(@"^Updated less than a minute ago$"), _ => "1 分钟内更新"),
        (new Regex(@"^Updated (\d+[mhd]) ago$"), m => $"{Loc.Duration(m.Groups[1].Value)}前更新"),
        (new Regex(@"^No data for (.+)$"), m => $"{m.Groups[1].Value} 没有数据"),
        (new Regex(@"^Usage lookup failed \((.+)\)$"), m => $"用量查询失败 — {LookupReason(m.Groups[1].Value)}"),
        (new Regex(@"^Cached values, lookup failing \((.+)\)$"), m => $"显示旧值 — {LookupReason(m.Groups[1].Value)}"),
        (new Regex(@"^Overage: (.+) / (.+)$"), m => $"超额使用：{m.Groups[1].Value} / {m.Groups[2].Value}"),
        (new Regex(@"^Balance: (.+) remaining$"), m => $"余额：{m.Groups[1].Value}"),
        (new Regex(@"^(.+) today  ·  (.+) / 30d$"), m => $"今天 {m.Groups[1].Value}  ·  30 天 {m.Groups[2].Value}"),
        (new Regex(@"^(\d+) profiles  ·  (\d+) at limit, (\d+) warning$"), m => $"{m.Groups[1].Value} 个账户  ·  已达上限 {m.Groups[2].Value}，警告 {m.Groups[3].Value}"),
        (new Regex(@"^(\d+) profiles  ·  (\d+) near limit$"), m => $"{m.Groups[1].Value} 个账户  ·  接近上限 {m.Groups[2].Value}"),
        (new Regex(@"^(\d+) profiles  ·  All healthy$"), m => $"{m.Groups[1].Value} 个账户  ·  全部正常"),
        (new Regex(@"^(\d+) profiles  ·  (\d+) need linking$"), m => $"{m.Groups[1].Value} 个账户  ·  需要关联 {m.Groups[2].Value}"),
    ];

    private static string Pace(string part)
    {
        var match = Regex.Match(part, @"^(\d+)% in (deficit|reserve)$");
        if (match.Success)
        {
            return match.Groups[2].Value == "deficit" ? $"超出 {match.Groups[1].Value}%" : $"富余 {match.Groups[1].Value}%";
        }

        match = Regex.Match(part, @"^Runs out in (.+)$");
        if (match.Success)
        {
            return $"{Loc.Duration(match.Groups[1].Value)}后用尽";
        }

        return part switch
        {
            "On pace" => "正常",
            "Unknown" => "未知",
            "Lasts until reset" => "可撑到重置",
            "Runs out now" => "即将用尽",
            _ => part
        };
    }
